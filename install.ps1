<#
    Installs the raop-sender background daemon.

    Run from an elevated PowerShell, in the directory containing raop-daemon.exe:

        .\install.ps1 -Receiver "192.0.2.10:5000"

    Configuration is written to raop-sender.env next to the executable, so the
    scheduled task picks it up immediately instead of waiting for a fresh logon.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Receiver,

    [string]$CaptureDevice = "CABLE",
    [string]$TaskName = "AirPlay Sender",
    [int]$PrimeMs = 60,
    [int]$BufferMs = 60
)

$ErrorActionPreference = "Stop"

$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    throw "Run this script from an elevated PowerShell."
}

if ($Receiver -notmatch ':\d+$') {
    throw "Receiver must be 'ip:port', for example 192.0.2.10:5000"
}

$exe = Join-Path $PSScriptRoot "raop-daemon.exe"
if (-not (Test-Path $exe)) {
    throw "raop-daemon.exe not found next to install.ps1. Build with: cargo build --release"
}

Write-Host "receiver : $Receiver"
Write-Host "capture  : $CaptureDevice"
Write-Host "binary   : $exe"

# The receiver sends timing requests back to the sender. Without this rule the
# stream is accepted and silently produces no audio, which is the single most
# common cause of "everything returns 200 and nothing plays".
Remove-NetFirewallRule -DisplayName $TaskName -ErrorAction SilentlyContinue
New-NetFirewallRule -DisplayName $TaskName -Direction Inbound -Program $exe `
    -Action Allow -Protocol UDP | Out-Null
Write-Host "firewall : inbound UDP allowed for the daemon"

$envFile = Join-Path $PSScriptRoot "raop-sender.env"
@(
    "# generated by install.ps1"
    "RAOP_HOST=$Receiver"
    "RAOP_DEVICE=$CaptureDevice"
    "RAOP_PRIME_MS=$PrimeMs"
    "RAOP_BUFFER_MS=$BufferMs"
) | Set-Content -Path $envFile -Encoding ASCII
Write-Host "config   : $envFile"

$action = New-ScheduledTaskAction -Execute $exe -WorkingDirectory $PSScriptRoot
$trigger = New-ScheduledTaskTrigger -AtLogOn
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
    -Settings $settings -RunLevel Highest -Force | Out-Null
Write-Host "task     : '$TaskName' registered at logon"

Write-Host ""
Write-Host "Start it now with:  Start-ScheduledTask -TaskName '$TaskName'"
Write-Host "Logs go to:         $(Join-Path $PSScriptRoot 'daemon.log')"
Write-Host "Remove it with:     Unregister-ScheduledTask -TaskName '$TaskName' -Confirm:`$false"
Write-Host "                    Remove-NetFirewallRule -DisplayName '$TaskName'"
